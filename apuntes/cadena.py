print ("h" in "hola")#in indica si h esta en hola
print ("h" not in "hola")#not in indica si h no esta en hola
print ("hola" == "hola")#== indica si hola es igual a hola
print ("hola" != "adios")#!= indica si hola es diferente a adios
print(len("hola"))#len indica la longitud de la cadena
print(min("hola"))#min indica el caracter menor en orden alfabetico
print(max("hola"))#max indica el caracter mayor en orden alfabetico
print("hola".upper())#upper convierte la cadena a mayusculas
print("HOLA".lower())#lower convierte la cadena a minusculas
print("hola".capitalize())#capitalize convierte la primera letra a mayuscula
print("me llamo aymane".split())#split divide la cadena en una lista de palabras
print("me llamo aymane".split("a"))#split divide la cadena en una lista de palabras usando a como separador
print("me llamo aymane".strip())#strip elimina los espacios en blanco al principio y al final de la cadena
print("me llamo aymane".replace("aymane","juan"))#replace reemplaza una palabra por otra
print("me llamo aymane".find("aymane"))#find busca una palabra en la cadena y devuelve su posicion
print("me llamo aymane".count("a"))#count cuenta el numero de veces que aparece una palabra en la cadena
print("aymane \n" *int(3))#\n indica un salto de linea y *int(3) indica que se repita 3 veces
